import math


# ------------------------------------------------------------
# Constants for species names and counts
# ------------------------------------------------------------
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"
TOTAL_SPECIES = 3

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

# ------------------------------------------------------------
# Functions for penguin analysis
# ------------------------------------------------------------
def calculate_percentage(count, total):
  return count / total * 100

def classify_species(percent):
  if percent < 25:
    return "small"
  elif percent < 40:
    return "medium"
  else:
    return "large"

def get_position_description(selected_species, largest_species, smallest_species):
  if selected_species == largest_species:
    return "largest"
  elif selected_species == smallest_species:
    return "smallest"
  else:
    return "middle-sized"


def display_species_statistics(names, counts, percentages):
  for index, species in enumerate(names):
    print(f"{species}: {counts[index]} ({percentages[index]:.2f}%)")


def main():
  # ------------------------------------------------------------
  # Parallel lists for species data
  # ------------------------------------------------------------
  species_names = [
      SP_CHINSTRAP,
      SP_GENTOO,
      SP_ADELIE
  ]

  species_counts = [
      NUM_CHINSTRAP,
      NUM_GENTOO,
      NUM_ADELIE
  ]


  # ------------------------------------------------------------
  # Calculate dataset statistics
  # ------------------------------------------------------------
  # Total number of species
  total_species = len(species_names)

  # Total number of penguins
  total_penguins = sum(species_counts)

  # Average number of penguins per species
  average_penguins = total_penguins / total_species

  # Rounded average
  rounded_average = round(average_penguins)

  # Percentage for each species

  chinstrap_percent = \
      calculate_percentage(species_counts[0], total_penguins)
  gentoo_percent = \
      calculate_percentage(species_counts[1], total_penguins)
  adelie_percent = \
      calculate_percentage(species_counts[2], total_penguins)

  # Third parallel list: species percentages
  species_percentages = [
      chinstrap_percent,
      gentoo_percent,
      adelie_percent
  ]

  # Largest and smallest species by count
  largest_count = max(species_counts)
  smallest_count = min(species_counts)

  largest_index = species_counts.index(largest_count)
  smallest_index = species_counts.index(smallest_count)

  largest_species = species_names[largest_index]
  smallest_species = species_names[smallest_index]


  # ------------------------------------------------------------
  # Output the species names with introductory text
  # ------------------------------------------------------------
  print("Introducing the Palmer Penguins:\n")
  print("    " + SP_CHINSTRAP + "!")
  print("    " + SP_GENTOO + "!")
  print("and last but not least...\n")
  print("    " + SP_ADELIE + "!\n")


  # ------------------------------------------------------------
  # Display calculated results
  # ------------------------------------------------------------
  print(f"There are a total of {TOTAL_SPECIES} species in this dataset.")
  print(f"There are a total of {total_penguins} penguins in the dataset.")
  print(f"The average number of penguins per species is {average_penguins:.1f}.")
  print(f"The average rounded up is {rounded_average} penguins.")

  # -------------------------------------------------------------------------
  # display species statistics using a function
  # -------------------------------------------------------------------------

  display_species_statistics(species_names,
                                 species_counts,
                                 species_percentages)
  print(f"The species with the most observations is {largest_species} "
        f"with {largest_count} penguins.")
  print(f"The species with the fewest observations is {smallest_species} "
        f"with {smallest_count} penguins.")
  print()


  # ------------------------------------------------------------
  # Initialize the valid selection counter
  # ------------------------------------------------------------
  valid_selections = 0


  # ------------------------------------------------------------
  # Repeatedly prompt the user to explore species
  # ------------------------------------------------------------
  print("Explore a species:")
  species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")

  while species_choice != "Done":

      # Validate the species selection
      if species_choice not in species_names:
          print(f"{species_choice} is not one of the species in this dataset.")

      else:
          # Update the number of valid selections
          valid_selections = valid_selections + 1

          # Determine the selected species index
          if species_choice == species_names[0]:
              selected_index = 0
          elif species_choice == species_names[1]:
              selected_index = 1
          else:
              selected_index = 2

          # Retrieve the selected species data
          selected_species = species_names[selected_index]
          selected_count = species_counts[selected_index]
          selected_percent = species_percentages[selected_index]

          # Classify the selected species using a function
          size_category = classify_species(selected_percent)

          # Determine the species position using a function
          position_description = \
              get_position_description(
                  selected_species,
                  largest_species,
                  smallest_species
              )

          # Compare the selected count to the average
          average_position = (
              "above" if selected_count > average_penguins else "below"
          )

          # Output selected species statistics
          print(f"{selected_species} has {selected_count} observations, "
                f"representing {selected_percent:.2f}% of the dataset.")
          print(f"{selected_species} is classified as a "
                f"{size_category} species group.")
          print(f"{selected_species} is the {position_description} "
                f"species group.")
          print(f"Its observation count is {average_position} "
                f"the dataset average of {average_penguins:.1f}.")

      print()
      species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")


  # ------------------------------------------------------------
  # Display the exploration summary
  # ------------------------------------------------------------
  print(f"You explored {valid_selections} valid species.")
  print("Exploration complete.")

main()

